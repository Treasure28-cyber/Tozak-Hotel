import assert from 'node:assert/strict';
import { initMotion } from '../src/assets/motion.js';
function setup(reduced = false, supported = true) {
  const animations = [];
  const listeners = {};
  const preference = {matches:reduced,addEventListener:(_,fn)=>listeners.preference=fn,removeEventListener:()=>delete listeners.preference};
  const element = () => ({hidden:false,parentElement:{children:[]},contains:target=>target==='focused',animate(frames,options){const animation={frames,options,cancelled:false,finished:new Promise(()=>{}),cancel(){this.cancelled=true;}};animations.push(animation);return animation;}});
  const heading=element(),card=element(),image=element();
  card.parentElement.children=[card];
  const observed=[];
  let callback;
  let disconnects=0;
  const view={matchMedia:()=>preference,Element:{prototype:supported?{animate(){}}:{}},IntersectionObserver:class{constructor(fn){callback=fn;}observe(el){observed.push(el);}unobserve(el){observed.splice(observed.indexOf(el),1);}disconnect(){disconnects++;}}};
  const doc={activeElement:null,querySelectorAll:selector=>selector.includes('.hero-copy')?[heading]:selector.includes('.hero-photo')?[image]:[card],addEventListener:(_,fn)=>listeners.focus=fn,removeEventListener:()=>delete listeners.focus};
  return {view,doc,heading,card,animations,observed,preference,listeners,intersect:()=>callback([{target:card,isIntersecting:true}]),get disconnects(){return disconnects;}};
}
const reduced=setup(true);
initMotion(reduced.view,reduced.doc);
assert.equal(reduced.animations.length,0,'Reduced motion starts no animations');
assert.equal(reduced.observed.length,0,'Reduced motion starts no observers');
const unsupported=setup(false,false);
initMotion(unsupported.view,unsupported.doc)();
assert.equal(unsupported.animations.length,0,'Missing animation API leaves content untouched');
const normal=setup();
const stop=initMotion(normal.view,normal.doc);
assert.equal(normal.animations.length,2,'Hero text and photograph animate');
assert.equal(normal.observed.length,1,'Below-fold card is observed');
normal.intersect();
assert.equal(normal.animations.length,3,'Visible card reveals');
normal.intersect();
assert.equal(normal.animations.length,3,'Cards reveal once');
normal.listeners.focus({target:'focused'});
assert.ok(normal.animations.every(a=>a.cancelled),'Keyboard focus cancels movement around focused content');
normal.preference.matches=true;
normal.listeners.preference();
assert.ok(normal.disconnects>0,'Preference change disconnects scroll observation');
assert.ok(normal.animations.every(a=>a.cancelled),'Preference change cancels active animations');
stop();
assert.equal(normal.listeners.preference,undefined,'Cleanup removes preference listener');
assert.equal(normal.listeners.focus,undefined,'Cleanup removes focus listener');
console.log('Passed: motion preferences, API fallback, one-time reveal, keyboard focus and cleanup.');
